Mỗi lần thổi saxophone, hơi thở mang theo hơi ẩm, nước bọt và cả những gì còn sót lại trong miệng đi thẳng vào kèn. Sau một buổi tập 30 phút, bên trong thân kèn đã đọng khá nhiều nước. Nếu cất kèn vào hộp ngay, lượng nước đó sẽ nằm lì trong kèn, thấm vào pad và cổ kèn cho đến lần thổi sau.

Vệ sinh kèn chỉ mất khoảng 5 phút mỗi buổi, nhưng đó là thói quen quyết định cây kèn của bạn giữ được âm thanh tốt trong bao lâu.

## Vì sao phải vệ sinh saxophone?

### 1. Bảo vệ pad – bộ phận dễ hỏng nhất

Pad là những miếng đệm bọc da dưới mỗi nắp phím, có nhiệm vụ đóng kín lỗ âm. Khi pad bị ướt thường xuyên:

- Da pad cứng lại, co ngót, nứt hoặc rách theo thời gian.
- Pad bị **dính**: phím mở chậm hoặc kêu "tạch" mỗi lần nhấc, đặc biệt là phím G#, phím C# và Eb thấp.
- Pad đóng không kín, gây **xì hơi (leak)** – nốt trầm khó ra, âm thanh bị vỡ, phải thổi mạnh hơn bình thường.

Thay một bộ pad tốn khá nhiều chi phí, nên giữ pad khô ráo là cách tiết kiệm nhất.

### 2. Tránh mùi hôi, nấm mốc và vi khuẩn

Béc và cổ kèn là nơi tiếp xúc trực tiếp với miệng. Nước bọt, đường từ đồ ăn thức uống đọng lại là môi trường lý tưởng cho vi khuẩn và nấm mốc phát triển, nhất là với khí hậu nóng ẩm và những ngày nồm ở Việt Nam. Ngoài mùi khó chịu, bạn đang đặt miệng lên một bề mặt bẩn mỗi lần thổi.

### 3. Ngăn cặn bám làm thay đổi âm thanh

Cặn từ nước bọt tích tụ dần thành lớp bám cứng bên trong béc và cổ kèn. Bên trong béc chỉ cần thay đổi một chút là âm sắc và độ nhạy đã khác đi, nên béc bẩn lâu ngày có thể khiến tiếng kèn tối, nặng và khó kiểm soát hơn.

### 4. Giữ bề mặt kèn không bị xỉn và oxy hóa

Mồ hôi tay có muối và axit. Nếu không lau, vân tay sẽ làm lớp sơn phủ (lacquer) bị xỉn, loang lổ, còn với kèn mạ bạc hoặc phần kim loại trần sẽ bị oxy hóa, đen và rỗ.

### 5. Kéo dài tuổi thọ và giữ giá trị cây kèn

Một cây kèn được chăm sóc tốt sẽ ít phải sửa vặt, cơ phím chạy êm, và nếu sau này muốn đổi kèn thì cũng bán lại được giá hơn hẳn. Khi kiểm tra một cây kèn cũ, tình trạng pad, cổ kèn và bề mặt là những thứ cho biết ngay chủ cũ có chăm sóc kèn hay không.

## Các dụng cụ vệ sinh saxophone

Bạn không cần mua tất cả cùng lúc. Ba món **bắt buộc** là que thông thân kèn, que thông béc/cổ kèn và khăn lau; các món còn lại có thể bổ sung dần.

### Que thông thân kèn (body swab) – bắt buộc

Một miếng vải dài (vải microfiber, cotton hoặc lụa) nối với sợi dây có quả nặng ở đầu. Dùng để thấm nước bên trong thân kèn sau mỗi lần thổi.

- Chọn đúng cỡ theo loại kèn (alto, tenor, soprano). Que quá to dễ bị kẹt trong thân kèn.
- Ưu tiên loại vải không xổ lông để không để lại sợi vải bên trong kèn.

### Que thông cổ kèn (neck swab) – bắt buộc

Cổ kèn là nơi đọng nhiều nước nhất. Có hai loại phổ biến: dạng dây kéo nhỏ giống que thông thân kèn, hoặc dạng que bông mềm luồn qua cổ kèn. Loại nào cũng được, miễn mềm và vừa với lòng cổ kèn.

### Que thông béc (mouthpiece swab hoặc cọ béc)

Dây kéo nhỏ hoặc cọ lông mềm dùng riêng cho béc. Tránh dùng cọ có lõi kim loại cứng vì có thể cào xước bên trong béc, đặc biệt là phần mép đầu béc (tip rail) và phần mặt tựa dăm – hai chỗ ảnh hưởng trực tiếp đến âm thanh.

### Khăn lau microfiber – bắt buộc

Dùng để lau vân tay và mồ hôi trên bề mặt kèn sau khi tập. Nên có một khăn riêng chỉ để lau kèn, giữ khăn sạch và khô. Một số hãng có khăn đánh bóng chuyên dụng cho kèn sơn phủ hoặc kèn mạ bạc.

### Giấy thấm pad

Giấy mỏng chuyên dụng để thấm nước và xử lý pad bị dính. Kẹp tờ giấy giữa pad và lỗ âm, ấn nhẹ phím vài giây rồi nhả phím ra trước khi rút giấy. Không kéo giấy khi phím đang đóng vì sẽ làm mòn mặt pad.

### Mỡ bôi nút bần (cork grease)

Bôi một lớp mỏng lên phần nút bần ở đầu cổ kèn để lắp béc vào dễ dàng, không làm nút bần bị khô, nứt. Bôi khi thấy lắp béc bị rít, không cần bôi mỗi ngày.

### Dầu tra phím (key oil)

Dầu chuyên dụng tra vào các trục phím để cơ phím chạy êm, không bị khô mòn. Chỉ cần tra rất ít, khoảng 6–12 tháng một lần. Nếu chưa tự tin, hãy để thợ làm khi bảo dưỡng định kỳ.

### Hộp đựng dăm

Dăm (lưỡi gà) sau khi thổi cần được lau sạch và cất vào hộp đựng dăm để dăm khô đều, phẳng, không cong vênh hay mốc. Đừng để dăm gắn trên béc khi cất kèn.

### Cọ mềm quét bụi

Một chiếc cọ nhỏ lông mềm (như cọ trang điểm hoặc cọ vẽ) để quét bụi bám dưới các thanh phím và quanh trụ phím – những chỗ khăn lau không với tới.

### Gói hút ẩm

Đặt một vài gói hút ẩm (silica gel) trong hộp kèn giúp hộp khô hơn, rất hữu ích vào mùa nồm ẩm. Nhớ thay hoặc sấy khô gói hút ẩm định kỳ.

