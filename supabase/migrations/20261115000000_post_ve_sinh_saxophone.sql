## Cách vệ sinh saxophone sau mỗi buổi tập

Cả quy trình mất khoảng 5 phút. Hãy làm ngay sau khi thổi xong, khi nước chưa kịp thấm vào pad.

**Bước 1 – Tháo dăm và béc.** Nới khóa béc, tháo dăm ra, lau nhẹ hai mặt dăm bằng khăn sạch rồi cất vào hộp đựng dăm. Sau đó vặn nhẹ để tháo béc khỏi cổ kèn.

**Bước 2 – Vệ sinh béc.** Luồn que thông béc qua béc 2–3 lần, kéo từ phần đuôi (đầu lắp vào cổ kèn) ra phía đầu béc. Lau sạch khóa béc.

**Bước 3 – Vệ sinh cổ kèn.** Tháo cổ kèn khỏi thân. Thả quả nặng của que thông cổ kèn vào từ đầu to (đầu lắp vào thân kèn), để dây chạy ra đầu nhỏ (đầu lắp béc), rồi kéo nhẹ que thông xuyên qua. Làm 2–3 lần. Cẩn thận với lỗ phím quãng tám trên cổ kèn, không thọc mạnh vật cứng vào đó.

**Bước 4 – Vệ sinh thân kèn.** Thả quả nặng vào loa kèn, xoay nghiêng kèn để quả nặng lăn xuống và chui ra ở đầu nhỏ (đầu lắp cổ kèn). Cầm dây kéo từ từ cho miếng vải đi hết thân kèn. Làm 2–3 lần cho đến khi vải không còn ướt nhiều.

> **Lưu ý:** Luôn kéo que thông đi một chiều, chậm và đều tay. Nếu que bị kẹt, **đừng giật mạnh** – thử kéo ngược lại theo hướng đã thả vào. Nếu vẫn không ra, mang kèn đến thợ thay vì cố kéo, vì giật mạnh có thể làm cong ống hoặc lệch phím.

**Bước 5 – Thấm nước ở pad.** Nhấn từng phím và quan sát, nếu thấy pad nào đọng nước (thường là G#, C# và Eb thấp) thì dùng giấy thấm hoặc góc khăn sạch thấm nhẹ.

**Bước 6 – Lau bề mặt kèn.** Dùng khăn microfiber lau vân tay, mồ hôi trên thân, cổ kèn và các phím bấm. Lau nhẹ nhàng, tránh để khăn vướng vào các lò xo kim nhỏ dưới phím vì có thể làm lò xo bị bật ra.

**Bước 7 – Để kèn khô rồi mới đóng hộp.** Nếu có thời gian, để kèn trên giá hoặc mở nắp hộp khoảng 15–30 phút cho bên trong khô hẳn. Que thông vừa dùng xong còn ướt nên để ra ngoài hộp cho khô, đừng nhét chung vào hộp kèn.

## Vệ sinh định kỳ

**Hàng tuần**

- Rửa béc bằng nước ấm (không dùng nước nóng) pha chút xà phòng nhẹ, dùng cọ mềm làm sạch bên trong, tráng lại bằng nước sạch và để khô tự nhiên. Béc nhựa cứng (ebonite) gặp nước nóng hoặc ánh nắng lâu sẽ bị ngả màu và có thể biến dạng.
- Dùng cọ mềm quét bụi quanh trụ phím và dưới các thanh phím.
- Giặt que thông, phơi khô hoàn toàn.

**Hàng tháng**

- Kiểm tra nút bần cổ kèn, bôi mỡ nếu thấy khô hoặc lắp béc bị rít.
- Kiểm tra pad xem có chỗ nào rách, phồng, dính hoặc đóng không kín.
- Kiểm tra các vít, nếu có vít lỏng thì báo thợ hoặc vặn lại nhẹ tay bằng tô vít đúng cỡ.

**Mỗi 6–12 tháng**

- Tra dầu trục phím.
- Mang kèn đến thợ để kiểm tra leak, cân chỉnh phím và thay pad nếu cần. Với người tập hằng ngày, bảo dưỡng tổng thể mỗi năm một lần là hợp lý.

## Những điều không nên làm

- **Không rửa nước cả thân kèn.** Pad bọc da sẽ hỏng ngay. Vệ sinh sâu bên trong thân kèn (tháo pad, tẩy cặn) là việc của thợ.
- **Không dùng cồn, nước rửa kính, chất tẩy mạnh** lên bề mặt kèn – lớp sơn phủ có thể bị bong, loang màu.
- **Không dùng kem/nước đánh bóng kim loại** lên kèn sơn phủ (lacquer). Loại này chỉ dành cho kim loại trần và dùng sai sẽ mài mất lớp sơn.
- **Không ăn kẹo, uống nước ngọt ngay trước khi thổi.** Nếu vừa ăn uống, hãy súc miệng hoặc đánh răng trước để đường và vụn thức ăn không đi vào kèn.
- **Không để kèn trong ô tô, chỗ nắng nóng hoặc nơi ẩm thấp** quá lâu.
- **Không tự tháo phím** nếu chưa có kinh nghiệm – lắp sai rất dễ gây leak và cong cần phím.

